"""Qualified PyVCD header inventory; no waveform database or HDL hierarchy claim."""
import hashlib
import importlib.metadata
import io
from pathlib import Path

from capture_core import NAME, PROFILE, digest, fingerprint, nullable, read_json, require, shape, text


def reader():
    try:
        version=importlib.metadata.version('pyvcd')
    except importlib.metadata.PackageNotFoundError as error:
        raise ValueError('Optional native VCD support needs pyvcd==0.5.0; see requirements-native-example.txt') from error
    require(version=='0.5.0','Qualified native VCD support requires pyvcd==0.5.0')
    from vcd.reader import tokenize, TokenKind
    return tokenize,TokenKind


def inspect_header(path):
    tokenize,Kind=reader()
    lines=[]
    with Path(path).open('rb') as stream:
        for line in stream:
            lines.append(line)
            if line.strip()==b'$enddefinitions $end':
                break
        else:
            raise ValueError('Complete native VCD enddefinitions marker required')
    raw=b''.join(lines)
    scopes=[];objects=[];names=set();widths={};tick=None;version=None;ended=False
    for token in tokenize(io.BytesIO(raw)):
        if token.kind is Kind.VERSION:
            require(version is None,'Repeated VCD version record')
            version=token.data
        elif token.kind is Kind.TIMESCALE:
            require(tick is None,'Repeated VCD timescale')
            tick={'value':str(token.data.magnitude),'unit':token.data.unit.value}
        elif token.kind is Kind.SCOPE:
            scopes.append(token.data.ident)
        elif token.kind is Kind.UPSCOPE:
            require(scopes,'Unbalanced VCD scope')
            scopes.pop()
        elif token.kind is Kind.VAR:
            item=token.data
            path='.'.join([*scopes,item.reference])
            require(scopes and path not in names,'Ambiguous or unscoped VCD object')
            names.add(path)
            require(item.id_code not in widths or widths[item.id_code]==item.size,'Alias declarations disagree about width')
            widths[item.id_code]=item.size
            selectable=bool(NAME.fullmatch(path)) and (item.bit_index is None or isinstance(item.bit_index,tuple))
            viewer=path
            if isinstance(item.bit_index,tuple):
                high,low=item.bit_index
                require(abs(high-low)+1==item.size,'Packed range disagrees with declared width')
                viewer+='[%d:%d]'%(high,low)
            elif item.bit_index is not None:
                viewer+='[%d]'%item.bit_index
            objects.append({'path':path,'id_code':item.id_code,'width':item.size,'kind':item.type_.value,
                            'selectable':selectable,'selector':path if selectable else None,'viewer_name':viewer})
        elif token.kind is Kind.ENDDEFINITIONS:
            require(not scopes,'VCD scope stack not closed')
            ended=True
            break
        elif token.kind not in (Kind.DATE,Kind.COMMENT):
            raise ValueError('Unsupported native VCD header record: '+token.kind.name)
    require(ended and tick is not None and version=='Generated by VerilatedVcd','Qualified VerilatedVcd header/timescale required')
    return {'format':'opentools.trace-header.v1','profile':PROFILE,'header_sha256':hashlib.sha256(raw).hexdigest(),
            'header_bytes':len(raw),'tick':tick,'objects':objects,
            'limits':'Complete VCD declaration namespace only; not full HDL hierarchy, original binary identity or recorded pre-history proof.'}


def context_template(header):
    return {'format':'opentools.trace-context.v1','profile':PROFILE,'producer_version':None,'binary_sha256':None,
            'header_sha256':header['header_sha256'],'max_tick':None,'trace_compiled':None,'evidence_ref':None,'aliases':[]}


def import_inventory(path,context):
    shape(context,('format','profile','producer_version','binary_sha256','header_sha256','max_tick','trace_compiled','evidence_ref','aliases'))
    require(context['format']=='opentools.trace-context.v1' and context['profile']==PROFILE
            and context['producer_version'] in ('5.020','5.020 2024-01-01'),'Verified producer declaration for Verilator 5.020 wrapper required')
    require((context['binary_sha256'] is None or digest(context['binary_sha256'])) and digest(context['header_sha256'])
            and (context['trace_compiled'] is None or type(context['trace_compiled']) is bool)
            and nullable(context['evidence_ref']) and isinstance(context['aliases'],list),'Invalid producer context')
    header=inspect_header(path)
    require(context['header_sha256']==header['header_sha256'],'Producer context does not bind this exact header prefix')
    result={'format':'opentools.trace-inventory.v1','profile':PROFILE,'namespace':'vcd_declarations',
            'binary_sha256':context['binary_sha256'],'tick':header['tick'],'trace_compiled':context['trace_compiled'],
            'max_tick':context['max_tick'],
            'complete':True,'objects':header['objects'],'aliases':context['aliases'],
            'source':{'header_sha256':header['header_sha256'],'context_sha256':fingerprint(context),'evidence_ref':context['evidence_ref']}}
    from capture_core import validate_inventory
    validate_inventory(result)
    return result


def write_viewer(recipe,path):
    reader()
    from vcd.gtkw import GTKWSave
    # Use the existing viewer's save format writer; no viewer or process is launched.
    with Path(path).open('x',encoding='utf-8',newline='\n') as stream:
        save=GTKWSave(stream)
        save.dumpfile(recipe['waveform_path'])
        save.timestart(recipe['viewer']['start_tick'])
        marker=recipe['viewer']['failure_tick']
        save.zoom_markers(marker=-1 if marker is None else marker)
        for name in recipe['viewer']['signals']:
            save.trace(name)
